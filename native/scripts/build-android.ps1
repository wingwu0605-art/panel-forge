# Build a debug APK for the Android shell. No system env vars needed.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File native/scripts/build-android.ps1
#
# It does four things:
#   1. find JDK + Android SDK (clear message if missing, instead of a gradle wall of errors)
#   2. sync site/ into native/www and run cap sync
#   3. write android/local.properties (gradle reads this, so no ANDROID_HOME needed)
#   4. run gradlew assembleDebug and print the APK path
# ASCII only: PowerShell 5.1 reads .ps1 as ANSI.
$ErrorActionPreference = 'Stop'

$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$native = (Resolve-Path (Join-Path $here '..')).Path
$root = (Resolve-Path (Join-Path $native '..')).Path

# ---- 0) node ----
$nodeCmd = Get-Command node -ErrorAction SilentlyContinue
if (-not $nodeCmd) {
  $guess = 'D:\nodejs'
  if (Test-Path (Join-Path $guess 'node.exe')) { $env:PATH = $guess + ';' + $env:PATH }
}
if (-not (Get-Command node -ErrorAction SilentlyContinue)) { throw 'node not found on PATH' }
Write-Host ("node: " + (node --version))

# ---- 1) JDK ----
$jdk = $env:JAVA_HOME
if (-not $jdk -or -not (Test-Path (Join-Path $jdk 'bin\java.exe'))) {
  $cands = @()
  $ms = Get-ChildItem 'C:\Program Files\Microsoft' -Filter 'jdk-*' -Directory -ErrorAction SilentlyContinue |
    Sort-Object Name -Descending | Select-Object -First 1
  if ($ms) { $cands += $ms.FullName }
  $ad = Get-ChildItem 'C:\Program Files\Eclipse Adoptium' -Filter 'jdk-*' -Directory -ErrorAction SilentlyContinue |
    Sort-Object Name -Descending | Select-Object -First 1
  if ($ad) { $cands += $ad.FullName }
  $cands += 'C:\Program Files\Android\Android Studio\jbr'
  $jdk = $cands | Where-Object { $_ -and (Test-Path (Join-Path $_ 'bin\java.exe')) } | Select-Object -First 1
  if (-not $jdk) { throw 'JDK not found: install JDK 17/21 (winget install Microsoft.OpenJDK.21)' }
}
$env:JAVA_HOME = $jdk
$env:PATH = (Join-Path $jdk 'bin') + ';' + $env:PATH
Write-Host ("JDK: " + $jdk)

# ---- 2) Android SDK ----
$sdk = $env:ANDROID_HOME
if (-not $sdk -or -not (Test-Path $sdk)) { $sdk = Join-Path $env:LOCALAPPDATA 'Android\Sdk' }
if (-not (Test-Path (Join-Path $sdk 'platform-tools'))) {
  throw ("Android SDK not found (" + $sdk + "): run native/scripts/install-sdk.ps1 first")
}
$env:ANDROID_HOME = $sdk
$env:ANDROID_SDK_ROOT = $sdk
$env:PATH = (Join-Path $sdk 'platform-tools') + ';' + $env:PATH
Write-Host ("Android SDK: " + $sdk)

# ---- 3) sync web assets + plugins ----
Push-Location $native
try {
  node scripts/sync-site.mjs
  npx cap sync android
} finally { Pop-Location }

# ---- 4) local.properties ----
$escaped = ($sdk -replace '\\', '\\')
$lp = "## generated by native/scripts/build-android.ps1 (do not commit)`nsdk.dir=$escaped`n"
Set-Content -Path (Join-Path $native 'android\local.properties') -Value $lp -Encoding ASCII

# ---- 5) build ----
Push-Location (Join-Path $native 'android')
try {
  if (-not (Test-Path 'gradlew.bat')) { throw 'android/gradlew.bat missing: run npx cap add android' }
  & .\gradlew.bat assembleDebug
  $apk = Join-Path (Get-Location).Path 'app\build\outputs\apk\debug\app-debug.apk'
  if (Test-Path $apk) {
    $mb = [math]::Round((Get-Item $apk).Length / 1MB, 1)
    Write-Host ""
    Write-Host ("APK built: " + $apk + " (" + $mb + " MB)")
    Write-Host ("Install: adb install -r `"" + $apk + "`"")
  }
} finally { Pop-Location }
